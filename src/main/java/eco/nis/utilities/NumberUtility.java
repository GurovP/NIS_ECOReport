package eco.nis.utilities;

public final class NumberUtility {
    public static final long oneSecMillis = 1000;
    public static final long halfMinMillis = 30 * oneSecMillis;
    public static final long oneMinMillis = 60 * oneSecMillis;
    public static final long oneHourMillis = 60 * oneMinMillis;
    public static final long oneDayMillis = 24 * oneHourMillis;
}
